#!/usr/bin/env node
/**
 * Bake public Supabase URL + anon key into desktop/runtime-config.cjs so packaged
 * Windows/Linux apps can call auto-attendance-event (Android embeds this via Capacitor).
 * Anon key is a public client credential — never put the service_role here.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const outPath = join(root, 'desktop', 'runtime-config.cjs');

function loadEnvFile(p) {
  const out = {};
  if (!p || !existsSync(p)) return out;
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!m) continue;
    out[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
  }
  return out;
}

const env = {
  ...loadEnvFile(join(homedir(), '.scorr', 'supabase.env')),
  ...loadEnvFile(process.env.SCORR_ENV_FILE || ''),
  ...loadEnvFile(join(root, '.env')),
  ...process.env,
};

const supabaseUrl =
  env.SCORR_SUPABASE_URL ||
  env.VITE_SUPABASE_URL ||
  'https://yvnbxweitelowucdhwpg.supabase.co';
const anonKey =
  env.SCORR_SUPABASE_ANON ||
  env.VITE_SUPABASE_ANON_KEY ||
  env.SUPABASE_ANON_KEY ||
  '';

if (!anonKey || anonKey.length < 20) {
  console.error(
    'write-desktop-runtime-config: missing VITE_SUPABASE_ANON_KEY / SCORR_SUPABASE_ANON — desktop auto check-in will not work.',
  );
  process.exit(1);
}

const body = `/** Auto-generated by scripts/write-desktop-runtime-config.mjs — do not edit. */
module.exports = {
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(anonKey)},
};
`;

writeFileSync(outPath, body, 'utf8');
console.log(`Wrote ${outPath} (anon key length ${anonKey.length})`);
